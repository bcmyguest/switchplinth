// Generates src/styles/tokens.css from src/theme.yml (a copy of the app's
// frontend/theme.yml) so the site shares the app's semantic colors.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = new URL('..', import.meta.url);
const theme = parse(readFileSync(new URL('src/theme.yml', root), 'utf8')).theme;
const { light, dark } = theme.semantic;

const vars = (tokens) =>
  Object.entries(tokens)
    .map(([name, value]) => `  --c-${name}: ${value};`)
    .join('\n');

// Starlight palette mapped onto the same tokens. Starlight's default
// (unattributed) root is dark; light overrides it.
const starlight = (t) => {
  return [
    `  --sl-color-accent-low: ${t['brand-soft']};`,
    `  --sl-color-accent: ${t.brand};`,
    `  --sl-color-accent-high: ${t.source};`,
    `  --sl-color-white: ${t.ink};`,
    `  --sl-color-gray-1: ${t.ink};`,
    `  --sl-color-gray-2: ${t.muted};`,
    `  --sl-color-gray-3: ${t.muted};`,
    `  --sl-color-gray-4: ${t.line};`,
    `  --sl-color-gray-5: ${t.line};`,
    `  --sl-color-gray-6: ${t['panel-raised']};`,
    `  --sl-color-gray-7: ${t.panel};`,
    `  --sl-color-black: ${t.canvas};`,
    `  --sl-color-bg-nav: ${t.panel};`,
    `  --sl-color-bg-sidebar: ${t.panel};`,
    `  --sl-color-hairline: ${t.line};`,
    `  --sl-color-hairline-light: ${t.line};`,
    `  --sl-color-hairline-shade: ${t.line};`,
  ].join('\n');
};

const css = `/* Generated by scripts/gen-theme.mjs from src/theme.yml. Do not edit. */
:root,
:root[data-theme='dark'] {
${vars(dark)}
  color-scheme: dark;
}
:root[data-theme='light'] {
${vars(light)}
  color-scheme: light;
}
/* Starlight palette */
:root,
:root[data-theme='dark'] {
${starlight(dark)}
}
:root[data-theme='light'] {
${starlight(light)}
}
`;

writeFileSync(fileURLToPath(new URL('src/styles/tokens.css', root)), css);
console.log('wrote src/styles/tokens.css');
